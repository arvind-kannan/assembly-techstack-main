"""Fail when a tracked data file holds an absolute path (AT 168, ADR-0009).

Paths in data files are relative to the file's own folder, so a case runs on every machine and in CI
(the product model loader resolves XML paths against the XML file's folder, AT 116).

Scans the tracked XML, URDF, SDF, xacro, JSON, YAML and INI files that `git ls-files` lists, minus
EXCLUDES. Flags POSIX paths under home, user, mount, temp, opt and similar system roots, Windows drive
paths with either slash, and `file://` URIs. `http(s)://` URLs, `package://` URIs and XML comments are
not flagged. Standalone on purpose (standard library only), so the CI job needs no `uv sync`.

Run `python tools/ci/check_absolute_paths.py` (or `uv run tools/ci/check_absolute_paths.py`) from
anywhere in the repo; pass file names to scan only those.
"""

import fnmatch
import re
import subprocess
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[2]

SCANNED_SUFFIXES = (".xml", ".urdf", ".sdf", ".xacro", ".json", ".yaml", ".yml", ".ini")
XML_SUFFIXES = (".xml", ".urdf", ".sdf", ".xacro")

POSIX_ROOTS = (
    "home", "Users", "user", "users", "mnt", "media", "Volumes", "tmp", "opt", "root",
    "var", "usr", "etc", "srv", "run", "private",
)  # fmt: skip
# A match must not continue a relative path (`meshes/home/x`, `../home/x`) or a URL (`host/home/x`).
_START = r"(?<![\w.~$%{}/\\:-])"
_TOKEN = r"""[^\s"'<>]*"""
ABSOLUTE_PATH = re.compile(
    rf"""file://{_TOKEN}"""  # file:// URI, any host or drive
    rf"""|{_START}/(?:{"|".join(POSIX_ROOTS)})/{_TOKEN}"""
    rf"""|(?<![A-Za-z0-9])[A-Za-z]:(?:\\\\|\\|/){_TOKEN}""",  # drive path, `\`, `\\` (JSON) or `/`
    re.IGNORECASE,
)
XML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)

# (glob on the repo-relative path, reason). Keep every entry's reason: nobody can fix these files.
EXCLUDES = (
    (".idea/*", "IDE settings folder: per machine"),
    ("*/.idea/*", "IDE settings folder: per machine"),
    (".vscode/*", "IDE settings folder: per machine"),
    ("*/.vscode/*", "IDE settings folder: per machine"),
    (
        ".claude/log/*",
        "agent log folder: run-record evidence holds absolute worktree paths; the release pipeline strips it",
    ),
    (
        "crc_disassembly_sim/docker-compose.yml",
        "cell simulation: mounts the host X11 socket, which has to be an absolute path",
    ),
    ("*.lock", "lock files: generated by the package manager"),
)

HINT = """\
Paths in data files are relative to the file's own folder, so cases run on every machine and in CI.
Make the path relative: the product model loader resolves XML paths against the XML file's folder
(e.g. `mesh_path="stl/part.stl"` next to the XML). If a file must hold an absolute path, add it to
EXCLUDES in tools/ci/check_absolute_paths.py with a reason."""


class Hit(NamedTuple):
    file: str
    line: int
    path: str


def is_excluded(name):
    return any(fnmatch.fnmatchcase(name, pattern) for pattern, _ in EXCLUDES)


def _blank_comments(text):
    """XML comments replaced by blanks, newlines kept so line numbers still match."""
    return XML_COMMENT.sub(lambda m: re.sub(r"[^\n]", " ", m.group()), text)


def scan(files):
    """Hits in `files`, a mapping of repo-relative name to file text; excluded and non-data files are skipped."""
    hits = []
    for name, text in files.items():
        suffix = Path(name).suffix.lower()
        if suffix not in SCANNED_SUFFIXES or is_excluded(name):
            continue
        if suffix in XML_SUFFIXES:
            text = _blank_comments(text)
        for number, line in enumerate(text.splitlines(), start=1):
            hits.extend(
                Hit(name, number, m.group()) for m in ABSOLUTE_PATH.finditer(line)
            )
    return hits


def tracked_files(root):
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True
    )
    return [n for n in out.stdout.decode("utf-8").split("\0") if n]


def main(argv=None, root=ROOT):
    names = argv if argv else tracked_files(root)
    files = {}
    for name in names:
        path = Path(root) / name
        if (
            Path(name).suffix.lower() in SCANNED_SUFFIXES
            and not is_excluded(name)
            and path.is_file()
        ):
            files[name] = path.read_text(encoding="utf-8", errors="replace")
    hits = scan(files)
    if not hits:
        return 0
    print(f"{len(hits)} absolute path(s) in tracked data files:\n", file=sys.stderr)
    for hit in hits:
        print(f"  {hit.file}:{hit.line}: {hit.path}", file=sys.stderr)
    print(f"\n{HINT}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
