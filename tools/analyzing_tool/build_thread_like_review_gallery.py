def key_dataset_case(row: dict[str, Any]) -> tuple[str, str]:
    return (
        str(row.get("_dataset") or row.get("group") or ""),
        str(row.get("assembly_name") or ""),
    )


def key_case_target(row: dict[str, Any]) -> tuple[str, str, str]:
    dataset = str(row.get("_dataset") or row.get("group") or "")
    case = str(row.get("assembly_name") or "")
    target = str(row.get("target_part") or "")
    return (dataset, case, target)


def build_case_index(
    rows: list[dict[str, str]],
) -> dict[tuple[str, str], dict[str, str]]:
    out: dict[tuple[str, str], dict[str, str]] = {}
    for row in rows:
        key = key_dataset_case(row)
        if key[1]:
            out[key] = row
            # Also allow lookup without dataset if unique enough.
            out[("", key[1])] = row
    return out


def build_pair_index(
    rows: list[dict[str, str]],
) -> dict[tuple[str, str, str], list[dict[str, str]]]:
    out: dict[tuple[str, str, str], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        dataset = str(row.get("_dataset") or row.get("group") or "")
        case = str(row.get("assembly_name") or "")
        target = str(row.get("target_part") or row.get("shaft_part") or "")
        if not case:
            continue
        out[(dataset, case, target)].append(row)
        out[("", case, target)].append(row)
    return out


def infer_dataset_from_case(case: str) -> str:
    if case.startswith("joint_assembly_rotation"):
        return "joint_assembly_rotation"
    if case.startswith("joint_assembly"):
        return "joint_assembly"
    if case.startswith("multi_assembly"):
        return "multi_assembly"
    return ""


def build_rendered_image_index(
    overview_manifest_rows: list[dict[str, str]],
) -> dict[tuple[str, str, str], str]:
    """
    Map (dataset/group, assembly_name, target_part) to output PNG path stem.

    overview_manifest.csv stores output_stem without extension.
    """
    out: dict[tuple[str, str, str], str] = {}
    for row in overview_manifest_rows:
        case = str(row.get("assembly_name") or "")
        target = str(row.get("target_part") or "")
        dataset = str(
            row.get("group") or row.get("_dataset") or infer_dataset_from_case(case)
        )
        output_stem = str(row.get("output_stem") or "")
        if not case or not output_stem:
            continue
        image_path = output_stem + ".png"
        key = (dataset, case, target)
        out[key] = image_path
        out[("", case, target)] = image_path
    return out


def guess_image_path(
    *,
    image_index: dict[tuple[str, str, str], str],
    image_root: Path | None,
    dataset: str,
    case: str,
    target: str,
) -> str:
    for key in [(dataset, case, target), ("", case, target)]:
        if key in image_index:
            return image_index[key]

    if image_root is not None:
        p = (
            image_root.expanduser().resolve()
            / safe_filename(dataset)
            / safe_filename(case)
            / f"target_{safe_filename(target)}_overview"
            / "00_assembly_overview.png"
        )
        if p.exists():
            return str(p)

    return ""


