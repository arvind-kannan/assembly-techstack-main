def conf_badge(conf: str) -> str:
    conf = normalize_conf(conf)
    return f'<span class="badge conf-{conf}">{safe_text(conf)}</span>'


def label_controls(item_idx: int) -> str:
    # Static HTML radio controls for convenient visual checking.
    # The choices are not automatically written back to CSV from a local file;
    # the CSV template remains the authoritative annotation target.
    name = f"label_{item_idx}"
    labels = ["TP-clear", "TP-weak", "FP", "unclear"]
    parts = []
    for lab in labels:
        parts.append(
            f'<label class="radio-label"><input type="radio" name="{name}" value="{safe_text(lab)}"> {safe_text(lab)}</label>'
        )
    return "\n".join(parts)


def pair_table(pairs: list[dict[str, str]], max_rows: int = 8) -> str:
    if not pairs:
        return '<div class="muted">No pair-level details found for this target.</div>'

    rows_html = []
    for p in pairs[:max_rows]:
        rows_html.append(
            "<tr>"
            f"<td>{safe_text(p.get('confidence') or p.get('confidence_norm'))}</td>"
            f"<td>{safe_text(p.get('score') or p.get('score_float') or p.get('thread_like_score'))}</td>"
            f"<td>{safe_text(p.get('relation'))}</td>"
            f"<td>{safe_text(p.get('target_part') or p.get('shaft_part'))}</td>"
            f"<td>{safe_text(p.get('paired_part') or p.get('ring_part') or p.get('other_part'))}</td>"
            f"<td>{safe_text(p.get('axis_alignment'))}</td>"
            f"<td>{safe_text(p.get('slenderness'))}</td>"
            "</tr>"
        )

    more = ""
    if len(pairs) > max_rows:
        more = f'<div class="muted">Showing {max_rows} of {len(pairs)} pair rows.</div>'

    return f"""
    <table class="small-table">
      <thead>
        <tr>
          <th>Conf.</th>
          <th>Score</th>
          <th>Relation</th>
          <th>Target/Shaft</th>
          <th>Paired</th>
          <th>Axis align.</th>
          <th>Slenderness</th>
        </tr>
      </thead>
      <tbody>
        {"".join(rows_html)}
      </tbody>
    </table>
    {more}
    """


def copy_images_to_gallery(
    items: list[dict[str, Any]], out_dir: Path, copy_images: bool
) -> None:
    if not copy_images:
        return

    img_dir = out_dir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)

    for idx, item in enumerate(items, start=1):
        raw = str(item.get("image_path") or "")
        if not raw:
            continue
        src = Path(raw)
        if not src.exists():
            continue
        dst_name = f"{idx:04d}_{safe_filename(item['dataset'])}_{safe_filename(item['assembly_name'])}_{safe_filename(item['target_part'])}.png"
        dst = img_dir / dst_name
        try:
            shutil.copy2(src, dst)
            item["image_path"] = str(dst)
        except Exception as exc:
            print(f"[WARN] Could not copy image {src}: {exc}")


