def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build an HTML gallery for manual validation of thread-like screening results."
    )
    parser.add_argument(
        "--sampling-plan",
        type=Path,
        required=True,
        help="manifest_sampling_plan.csv from analyze_thread_like_screening_results.py.",
    )
    parser.add_argument(
        "--overview-manifest",
        type=Path,
        default=None,
        help="overview_manifest.csv from render_failure_case_overviews.py.",
    )
    parser.add_argument(
        "--case-summary",
        type=Path,
        default=None,
        help="combined_case_summary.csv from analyze_thread_like_screening_results.py.",
    )
    parser.add_argument(
        "--pair-summary",
        type=Path,
        default=None,
        help="combined_pair_summary.csv from analyze_thread_like_screening_results.py.",
    )
    parser.add_argument(
        "--image-root",
        type=Path,
        default=None,
        help="Optional root folder containing rendered overview images if no overview_manifest is provided.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Output folder for index.html and manual_validation_template.csv.",
    )
    parser.add_argument(
        "--min-confidence",
        choices=["possible", "likely", "high"],
        default=None,
        help="Only include rows at or above this confidence.",
    )
    parser.add_argument(
        "--max-items",
        type=int,
        default=None,
        help="Optional maximum number of review items.",
    )
    parser.add_argument(
        "--copy-images",
        action="store_true",
        help="Copy referenced overview images into the gallery folder for portable sharing.",
    )
    parser.add_argument(
        "--title",
        type=str,
        default="Thread-like Screening Review Gallery",
        help="HTML page title.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    out_dir = args.out.expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    sampling_rows = read_csv_rows(args.sampling_plan)
    overview_rows = read_csv_rows(args.overview_manifest)
    case_rows = read_csv_rows(args.case_summary)
    pair_rows = read_csv_rows(args.pair_summary)

    if not sampling_rows:
        raise ValueError(f"No sampling rows loaded from {args.sampling_plan}")

    case_index = build_case_index(case_rows)
    pair_index = build_pair_index(pair_rows)
    image_index = build_rendered_image_index(overview_rows)

    items = prepare_items(
        sampling_rows,
        case_index=case_index,
        pair_index=pair_index,
        image_index=image_index,
        image_root=args.image_root.expanduser().resolve() if args.image_root else None,
        min_confidence=args.min_confidence,
        max_items=args.max_items,
    )

    copy_images_to_gallery(items, out_dir, copy_images=bool(args.copy_images))

    manual_rows = make_manual_validation_rows(items)
    manual_fields = [
        "_dataset",
        "assembly_name",
        "target_part",
        "confidence",
        "score",
        "relation",
        "paired_part",
        "completion",
        "failure_relevant_thread_like",
        "image_path",
        "manual_label",
        "manual_note",
    ]
    write_csv_rows(
        out_dir / "manual_validation_template.csv", manual_rows, manual_fields
    )

    html_text = build_html(items, out_dir=out_dir, title=args.title)
    (out_dir / "index.html").write_text(html_text, encoding="utf-8")

    summary = {
        "sampling_plan": str(args.sampling_plan.expanduser().resolve()),
        "overview_manifest": str(args.overview_manifest.expanduser().resolve())
        if args.overview_manifest
        else None,
        "case_summary": str(args.case_summary.expanduser().resolve())
        if args.case_summary
        else None,
        "pair_summary": str(args.pair_summary.expanduser().resolve())
        if args.pair_summary
        else None,
        "out": str(out_dir),
        "num_items": len(items),
        "num_missing_images": sum(
            1
            for i in items
            if not str(i.get("image_path") or "")
            or not Path(str(i.get("image_path"))).exists()
        ),
        "confidence_counts": dict(
            Counter(normalize_conf(i.get("confidence")) for i in items)
        ),
    }
    (out_dir / "gallery_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )

    print("=" * 80)
    print(f"[DONE] Gallery items: {len(items)}")
    print(f"[DONE] Output folder: {out_dir}")
    print(f"[DONE] HTML: {out_dir / 'index.html'}")
    print(f"[DONE] Manual validation CSV: {out_dir / 'manual_validation_template.csv'}")
    print(f"[DONE] Missing images: {summary['num_missing_images']}")


if __name__ == "__main__":
    main()
