def read_csv_rows(path: Path | None) -> list[dict[str, str]]:
    if path is None:
        return []
    path = path.expanduser().resolve()
    if not path.exists():
        print(f"[WARN] CSV does not exist: {path}")
        return []
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def write_csv_rows(
    path: Path, rows: list[dict[str, Any]], fieldnames: list[str]
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in fieldnames})


def normalize_conf(value: Any) -> str:
    s = str(value or "").strip().lower()
    if s in {"possible", "likely", "high"}:
        return s
    return "none"


def conf_rank(value: Any) -> int:
    return CONF_RANK.get(normalize_conf(value), 0)


def parse_float(value: Any, default: float | None = None) -> float | None:
    try:
        if value in (None, ""):
            return default
        return float(value)
    except Exception:
        return default


def parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value in (None, ""):
        return False
    return str(value).strip().lower() in {"true", "1", "yes", "y", "t"}


def safe_text(value: Any) -> str:
    return html.escape(str(value if value is not None else ""))


def safe_filename(text: str) -> str:
    out = []
    for ch in str(text):
        if ch.isalnum() or ch in {"_", "-", "."}:
            out.append(ch)
        else:
            out.append("_")
    return "".join(out)


def relpath_or_abs(path: Path, base: Path) -> str:
    try:
        return str(path.resolve().relative_to(base.resolve()))
    except Exception:
        return str(path.resolve())


