def prepare_items(
    sampling_rows: list[dict[str, str]],
    *,
    case_index: dict[tuple[str, str], dict[str, str]],
    pair_index: dict[tuple[str, str, str], list[dict[str, str]]],
    image_index: dict[tuple[str, str, str], str],
    image_root: Path | None,
    min_confidence: str | None,
    max_items: int | None,
) -> list[dict[str, Any]]:
    min_rank = conf_rank(min_confidence) if min_confidence else 0
    items: list[dict[str, Any]] = []

    for row in sampling_rows:
        case = str(row.get("assembly_name") or "")
        if not case:
            continue
        dataset = str(
            row.get("_dataset") or row.get("group") or infer_dataset_from_case(case)
        )
        target = str(row.get("target_part") or "")
        conf = normalize_conf(row.get("confidence") or row.get("confidence_norm"))

        if conf_rank(conf) < min_rank:
            continue

        case_info = case_index.get((dataset, case)) or case_index.get(("", case)) or {}
        pairs = (
            pair_index.get((dataset, case, target))
            or pair_index.get(("", case, target))
            or []
        )

        image_path = guess_image_path(
            image_index=image_index,
            image_root=image_root,
            dataset=dataset,
            case=case,
            target=target,
        )

        items.append(
            {
                "dataset": dataset,
                "assembly_name": case,
                "target_part": target,
                "confidence": conf,
                "score": row.get("score") or row.get("score_float") or "",
                "relation": row.get("relation") or "",
                "paired_part": row.get("paired_part") or row.get("other_part") or "",
                "sampling_confidence_group": row.get("sampling_confidence_group")
                or conf,
                "source_xml": row.get("xml_path") or case_info.get("xml_path") or "",
                "source_jsonl": row.get("source_jsonl")
                or case_info.get("source_jsonl")
                or "",
                "completion": row.get("completion")
                or case_info.get("completion")
                or "",
                "stop_reason": row.get("stop_reason")
                or case_info.get("stop_reason")
                or "",
                "report_success": row.get("report_success")
                or case_info.get("report_success")
                or "",
                "failure_relevant": (
                    row.get("failure_relevant_thread_like")
                    or case_info.get("failure_relevant_thread_like")
                    or ""
                ),
                "max_confidence": case_info.get("max_confidence")
                or case_info.get("max_confidence_norm")
                or "",
                "max_score": case_info.get("max_thread_like_score")
                or case_info.get("max_score")
                or "",
                "num_detected_pairs": case_info.get("num_detected_pairs") or "",
                "num_likely_or_high_pairs": case_info.get("num_likely_or_high_pairs")
                or "",
                "num_high_confidence_pairs": case_info.get("num_high_confidence_pairs")
                or "",
                "image_path": image_path,
                "pairs": pairs,
                "manual_label": row.get("manual_label") or "",
                "manual_note": row.get("manual_note") or "",
            }
        )

    def sort_key(item: dict[str, Any]) -> tuple[int, float, str]:
        return (
            -conf_rank(item.get("confidence")),
            -(parse_float(item.get("score"), 0.0) or 0.0),
            str(item.get("assembly_name")),
        )

    items.sort(key=sort_key)

    if max_items is not None:
        items = items[: max(0, max_items)]

    return items


def make_manual_validation_rows(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = []
    for item in items:
        rows.append(
            {
                "_dataset": item.get("dataset", ""),
                "assembly_name": item.get("assembly_name", ""),
                "target_part": item.get("target_part", ""),
                "confidence": item.get("confidence", ""),
                "score": item.get("score", ""),
                "relation": item.get("relation", ""),
                "paired_part": item.get("paired_part", ""),
                "completion": item.get("completion", ""),
                "failure_relevant_thread_like": item.get("failure_relevant", ""),
                "image_path": item.get("image_path", ""),
                "manual_label": item.get("manual_label", ""),
                "manual_note": item.get("manual_note", ""),
            }
        )
    return rows


