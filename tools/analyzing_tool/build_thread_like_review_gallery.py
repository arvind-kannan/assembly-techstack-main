"""
Build an HTML review gallery for thread-like screening manual validation.

Purpose
-------
This tool connects the thread-like screening sampling plan with rendered overview
figures, so the user can inspect cases in a browser and label them as:

    TP-clear, TP-weak, FP, unclear

It reads:
    - manifest_sampling_plan.csv generated by analyze_thread_like_screening_results.py
    - optional overview_manifest.csv generated by render_failure_case_overviews.py
    - optional combined_case_summary.csv
    - optional combined_pair_summary.csv

It writes:
    - index.html
    - manual_validation_template.csv

Typical workflow
----------------

1) Render overview images for the sampling plan:

cd <repo>

PYTHONPATH=src:$PYTHONPATH \
python tools/rendering_tool/render_failure_case_overviews.py \
  --manifest ../private/results/thread_like_screening_joint/analysis/manifest_sampling_plan.csv \
  --manifest-min-confidence likely \
  --formats png \
  --out ../private/figures/thread_like_joint_validation/high_likely

2) Build the review gallery:

python tools/analyzing_tool/build_thread_like_review_gallery.py \
  --sampling-plan ../private/results/thread_like_screening_joint/analysis/manifest_sampling_plan.csv \
  --overview-manifest ../private/figures/thread_like_joint_validation/high_likely/overview_manifest.csv \
  --case-summary ../private/results/thread_like_screening_joint/analysis/combined_case_summary.csv \
  --pair-summary ../private/results/thread_like_screening_joint/analysis/combined_pair_summary.csv \
  --out ../private/results/thread_like_screening_joint/review_gallery_high_likely \
  --min-confidence likely

3) Open:
    firefox ../private/results/thread_like_screening_joint/review_gallery_high_likely/index.html

4) Fill labels in:
    manual_validation_template.csv

5) Rerun analysis with:
    --manual-validation manual_validation_template.csv
"""

